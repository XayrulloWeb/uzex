export type Lang = 'ru' | 'uz';
export type Scope = {
  year: number;
  region: string;
  commodity: string;
  status: 'all' | 'active' | 'fulfilled';
};
export type Region = { id: string; raw: string; ru: string; uz: string; lng: number; lat: number };
export type Commodity = { id: string; code: string; ru: string; uz: string };
export type Catalog = {
  regions: Region[];
  commodities: Commodity[];
  years: number[];
  total_deals: number;
  ai_enabled: boolean;
  snapshot: string;
};
export type RegionStat = { id: string; deals: number; amount_uzs: string };
export type Monthly = { period: string; deals: number; amount_uzs: string };
export type Route = { origin: string; destination: string; deals: number; amount_uzs: string };
export type Overview = {
  metrics: {
    deals: number;
    amount_uzs: string;
    sellers: number;
    buyers: number;
    cancelled: number;
    fulfilled: number;
    export_deals: number;
    export_amount_uzs: string;
    first_date: string | null;
    last_date: string | null;
  };
  monthly: Monthly[];
  regions: RegionStat[];
  commodities: RegionStat[];
  routes: Route[];
  snapshot: string;
  total_dataset_deals: number;
};
export type DealRow = {
  deal_id: number;
  deal_date: string;
  contract_id: string;
  product_label: string;
  commodity: string;
  region: string;
  lot_count: string;
  lot_size: string;
  quantity: string;
  unit: string;
  amount_native: string;
  currency: string;
  amount_uzs: string;
  status: string;
  seller_name: string;
  seller_inn: string;
  buyer_name: string;
  buyer_inn: string;
};
